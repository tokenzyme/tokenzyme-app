import { IconQuestionMark } from '@tabler/icons-react';
import { Avatar } from 'primereact/avatar';
import { Card } from 'primereact/card';
import { Fragment, JSX } from 'react';
import { Link } from 'react-router';

import { useDependencies } from './TradingFeeShareHooks';

import { SuspenseSpinner } from '@design/components/SuspenseSpinner';
import { formatAccountAddress } from '@utils/blockchain';

export function TradingFeeShareContent(): JSX.Element {
  const { promotedTokens } = useDependencies();

  return (
    <div className="grid grid-cols-1 gap-2 sm:grid-cols-2 md:grid-cols-3 xl:grid-cols-4">
      {promotedTokens.map(({ token, position, tradeFeeShare }) => (
        <Fragment key={position}>
          {token ? (
            <Link key={position} to={`/tokens/${token.address}`}>
              <Card>
                <div className="flex gap-4">
                  <Avatar
                    image={token.logoUrl}
                    size="xlarge"
                    className="shrink-0"
                    pt={{ image: { className: 'rounded-md' } }}
                  />
                  <div className="grow">
                    <h2 className="!text-xl">{token.name}</h2>
                    <div className="flex flex-col gap-1 text-sm text-secondary">
                      <span className="font-bold">{token.symbol}</span>
                      <span>Trading fee share: {tradeFeeShare}%</span>
                      <span>Creator: {formatAccountAddress(token.creatorAddress)}</span>
                    </div>
                  </div>
                </div>
              </Card>
            </Link>
          ) : (
            <div key={position}>
              <Card className="shrink">
                <div className="flex gap-4 items-center">
                  <Avatar size="xlarge" className="rounded-md shrink-0">
                    <IconQuestionMark size={32} />
                  </Avatar>
                  <div className="grow">
                    <h2 className="!text-xl">{position} Token</h2>
                    <span className="text-sm text-secondary">Trading fee share: {tradeFeeShare}%</span>
                  </div>
                </div>
              </Card>
            </div>
          )}
        </Fragment>
      ))}
    </div>
  );
}

export function TradingFeeShare(): JSX.Element {
  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-col gap-2">
        <h2>Trading Fee Share</h2>
        <span className="text-secondary">
          Every month, the creators of the first 3 tokens promoted to the DEX are rewarded with a percentage of the
          trading fees generated by their tokens.
        </span>
      </div>
      <SuspenseSpinner>
        <TradingFeeShareContent />
      </SuspenseSpinner>
      <div className="text-secondary">
        * The Trading Fee Share may be distributed at any time within one month after the token is promoted.
      </div>
    </div>
  );
}
